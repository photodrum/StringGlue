const H = require('./harness.js');
const { srcFrame, font, rgb } = H;
const BLACK = rgb(0,0,0), GRAY = rgb(120,120,120), RED = rgb(200,0,0);
const st = (size, f = 'Reg', fill = BLACK, extra = {}) => Object.assign({ size, textFont: font(f), fillColor: fill }, extra);

// одна строка исходника; split: 'letters' | 'words' | 'line'; runs: [[text, style], ...]
function line(runs, base, split = 'letters', x0 = 0) {
  const out = []; let x = x0;
  if (!Array.isArray(runs)) runs = [[runs, split.style]];
  for (const [text, a] of runs) {
    const adv = a.size * 0.6;
    if (split === 'line') { out.push(srcFrame(text, x, base + (a.baselineShift || 0), a)); x += text.length * adv; continue; }
    const parts = split === 'words' ? text.split(/(\s+)/) : [...text];
    for (const t of parts) {
      if (/^\s+$/.test(t)) { x += a.size * 0.3 * t.length; continue; }
      if (!t) continue;
      out.push(srcFrame(t, x, base, a)); x += t.length * adv;
    }
    if (/\s$/.test(text)) {} // trailing space handled by advance
  }
  return out;
}
const L = (text, style, base, split = 'letters', x0 = 0) => line([[text, style]], base, split, x0);

